#!/usr/bin/env python3
"""Turn a Navi33 SMU/PMFW image into a local C header.

Example:
    python3 tools/gen_smu_fw_header.py \
      smu_13_0_10.bin RedNavi/smu_fw.h \
      --expected-sha256 d6c5a9fa211985ab00438955931adff5eaf456794d38b198ce92ff39d283dc26

The emitted payload is exactly what Linux hands to PSP for
AMDGPU_UCODE_ID_SMC / GFX_FW_TYPE_SMU: ucode_size_bytes bytes beginning at
ucode_array_offset_bytes. Firmware remains local and must not be committed.
"""
import argparse
import hashlib
import os
import struct


TARGET_BASENAME = "smu_13_0_10.bin"


def parse_args(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("source")
    ap.add_argument("output")
    ap.add_argument("--expected-sha256")
    return ap.parse_args(argv)


def parse_firmware(data):
    if len(data) < 32:
        raise ValueError("firmware is smaller than the common AMD header")

    (size_bytes, hdr_size, vmaj, vmin, imaj, imin, ucode_version,
     ucode_size, array_off, crc) = struct.unpack_from("<IIHHHHIIII", data, 0)

    if size_bytes != len(data):
        raise ValueError(
            f"file size mismatch: file={len(data)} header={size_bytes}"
        )
    if hdr_size < 32 or hdr_size > len(data):
        raise ValueError(f"invalid header size {hdr_size}")
    if array_off < hdr_size or array_off > len(data):
        raise ValueError(f"invalid ucode offset {array_off}")
    if ucode_size == 0 or array_off + ucode_size > len(data):
        raise ValueError(
            f"ucode is out of bounds: off={array_off} size={ucode_size}"
        )

    return {
        "header_size": hdr_size,
        "header_version_major": vmaj,
        "header_version_minor": vmin,
        "ip_major": imaj,
        "ip_minor": imin,
        "ucode_version": ucode_version,
        "ucode_size": ucode_size,
        "ucode_offset": array_off,
        "crc": crc,
        "payload": data[array_off:array_off + ucode_size],
    }


def main(argv=None):
    args = parse_args(argv)
    data = open(args.source, "rb").read()
    meta = parse_firmware(data)

    digest = hashlib.sha256(data).hexdigest()
    expected = args.expected_sha256.lower() if args.expected_sha256 else None
    trusted = bool(expected and digest == expected)

    if expected and digest != expected:
        raise SystemExit(
            f"SHA-256 mismatch: expected {expected}, got {digest}"
        )

    basename_ok = os.path.basename(args.source) == TARGET_BASENAME
    if not basename_ok:
        raise SystemExit(
            f"expected {TARGET_BASENAME}, got {os.path.basename(args.source)}"
        )

    with open(args.output, "w") as f:
        f.write(
            f"// Generated by tools/gen_smu_fw_header.py from "
            f"{TARGET_BASENAME}. Do not commit.\n"
        )
        f.write("#define RN_SMU_FW_METADATA_V1 1\n")
        f.write(f"#define RN_SMU_FW_DIGEST_TRUSTED {1 if trusted else 0}\n")
        f.write(f"#define kRNSmuFwSourceBytes {len(data)}u\n")
        f.write(f"#define kRNSmuFwHeaderSize {meta['header_size']}u\n")
        f.write(f"#define kRNSmuFwUcodeOffset {meta['ucode_offset']}u\n")
        f.write(
            f"#define kRNSmuFwVersion 0x{meta['ucode_version']:x}u\n"
        )
        f.write(f"#define kRNSmuFwSize {meta['ucode_size']}u\n")
        f.write(
            f"static const char kRNSmuFwSourceSha256[] = "
            f"\"{digest}\";\n"
        )
        f.write("static const unsigned char kRNSmuFw[] = {\n")
        payload = meta["payload"]
        for j in range(0, len(payload), 16):
            f.write(
                "    " +
                ", ".join(f"0x{x:02x}" for x in payload[j:j + 16]) +
                ",\n"
            )
        f.write("};\n")

    print(
        f"header v{meta['header_version_major']}."
        f"{meta['header_version_minor']}, "
        f"ip {meta['ip_major']}.{meta['ip_minor']}, "
        f"ucode version 0x{meta['ucode_version']:x}, "
        f"{meta['ucode_size']} bytes, "
        f"sha256 {digest}, trusted={int(trusted)}"
    )


if __name__ == "__main__":
    main()
